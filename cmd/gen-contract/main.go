package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"hdu-library-sniper/internal/api"
	"hdu-library-sniper/internal/core"
)

const outputPath = "src/shared/api.generated.ts"

type enumDef struct {
	name   string
	values string
}

var enums = []enumDef{
	{name: "Weekday", values: "1 | 2 | 3 | 4 | 5 | 6 | 7"},
	{name: "PlanToggleAction", values: `"enable" | "disable"`},
	{name: "BookingAction", values: `"cancel" | "checkin" | "comeback" | "signout" | "leave"`},
	{name: "BookingState", values: `"pending" | "check_in" | "in_use" | "away"`},
	{name: "NextTargetKind", values: `"booking" | "check-in" | "none"`},
	{name: "QrLoginPhase", values: `"pending" | "success" | "expired" | "error"`},
	{name: "AppEventKind", values: `"session" | "runtime" | "invalidate" | "audit"`},
	{name: "InvalidateTarget", values: `"plans" | "bookings" | "nextTarget" | "checkin" | "runtime"`},
}

func main() {
	check := flag.Bool("check", false, "verify generated file matches committed output without writing")
	flag.Parse()

	src := generate()
	if *check {
		existing, err := os.ReadFile(outputPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "read %s: %v\n", outputPath, err)
			os.Exit(1)
		}
		if !bytes.Equal(existing, []byte(src)) {
			fmt.Fprintf(os.Stderr, "%s is out of date; run: go run ./cmd/gen-contract\n", outputPath)
			os.Exit(1)
		}
		return
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(outputPath, []byte(src), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", outputPath, err)
		os.Exit(1)
	}
}

func generate() string {
	planListItemType := reflect.TypeFor[core.PlanListItem]()
	structs := map[string]reflect.Type{}
	responseSchemas := map[string]reflect.Type{}

	var collect func(t reflect.Type)
	collect = func(t reflect.Type) {
		for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {
			t = t.Elem()
		}
		if t.Kind() != reflect.Struct {
			return
		}
		if t == planListItemType {
			collect(reflect.TypeFor[core.BookingPlan]())
			collect(reflect.TypeFor[core.BookingGroup]())
			return
		}
		name := t.Name()
		if name == "" {
			return
		}
		if _, ok := structs[name]; ok {
			return
		}
		structs[name] = t
		for i := range t.NumField() {
			f := t.Field(i)
			if !f.IsExported() || jsonFieldName(f) == "" {
				continue
			}
			collect(f.Type)
		}
	}

	collect(reflect.TypeFor[api.ErrorResponse]())
	for _, ep := range api.Endpoints {
		if ep.RequestType != nil {
			collect(ep.RequestType)
		}
		if ep.ResponseType != nil {
			collect(ep.ResponseType)
			responseSchemas[ep.ResponseType.Name()] = ep.ResponseType
		}
	}

	typeNames := make([]string, 0, len(structs))
	for name := range structs {
		typeNames = append(typeNames, name)
	}
	sort.Strings(typeNames)

	schemaNames := make([]string, 0, len(responseSchemas))
	for name := range responseSchemas {
		schemaNames = append(schemaNames, name)
	}
	sort.Strings(schemaNames)

	var b strings.Builder
	b.WriteString("// Code generated by `go run ./cmd/gen-contract`. DO NOT EDIT.\n\n")

	for _, e := range enums {
		fmt.Fprintf(&b, "export type %s = %s;\n", e.name, e.values)
	}
	b.WriteString("\n")

	for _, name := range typeNames {
		writeStructType(&b, name, structs[name])
		b.WriteString("\n")
	}
	b.WriteString("export type PlanListItem = BookingPlan | BookingGroup;\n\n")

	b.WriteString("export type APIEndpoints = {\n")
	for _, ep := range api.Endpoints {
		fmt.Fprintf(&b, "  %s: {\n", ep.Name)
		fmt.Fprintf(&b, "    method: %q;\n", ep.Method)
		fmt.Fprintf(&b, "    pattern: %q;\n", ep.Path)
		if len(ep.PathParams) > 0 {
			writeParamObject(&b, "pathParams", ep.PathParams)
		}
		if len(ep.QueryParams) > 0 {
			hasReq := false
			for _, p := range ep.QueryParams {
				if p.Required {
					hasReq = true
					break
				}
			}
			key := "query?"
			if hasReq {
				key = "query"
			}
			writeParamObject(&b, key, ep.QueryParams)
		}
		if ep.RequestType != nil {
			fmt.Fprintf(&b, "    request: %s;\n", tsType(ep.RequestType, ""))
		}
		fmt.Fprintf(&b, "    response: %s;\n", tsType(ep.ResponseType, ""))
		b.WriteString("  };\n")
	}
	b.WriteString("};\n\n")

	b.WriteString("export const API_SCHEMAS = {\n")
	for _, name := range schemaNames {
		writeSchemaEntry(&b, name, responseSchemas[name])
	}
	b.WriteString("} as const;\n\n")

	b.WriteString("export const API_ROUTES = {\n")
	for _, ep := range api.Endpoints {
		fmt.Fprintf(&b, "  %s: {\n", ep.Name)
		fmt.Fprintf(&b, "    method: %q,\n", ep.Method)
		fmt.Fprintf(&b, "    pattern: %q,\n", ep.Path)
		fmt.Fprintf(&b, "    schema: %q,\n", ep.ResponseType.Name())
		b.WriteString("  },\n")
	}
	b.WriteString(
		"} as const satisfies Record<\n" +
			"  keyof APIEndpoints,\n" +
			"  { method: string; pattern: string; schema: keyof typeof API_SCHEMAS }\n" +
			">;\n",
	)

	return b.String()
}

func writeParamObject(b *strings.Builder, field string, params []api.ParamSpec) {
	fmt.Fprintf(b, "    %s: {\n", field)
	for _, p := range params {
		opt := ""
		if !p.Required {
			opt = "?"
		}
		fmt.Fprintf(b, "      %s%s: %s;\n", p.Name, opt, p.TypeExpr)
	}
	b.WriteString("    };\n")
}

func writeStructType(b *strings.Builder, name string, t reflect.Type) {
	fmt.Fprintf(b, "export type %s = {\n", name)
	for i := range t.NumField() {
		f := t.Field(i)
		jsonName := jsonFieldName(f)
		if !f.IsExported() || jsonName == "" {
			continue
		}
		opt := ""
		if hasOmitEmpty(f) {
			opt = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", jsonName, opt, tsType(f.Type, f.Tag.Get("contract")))
	}
	b.WriteString("};\n")
}

func writeSchemaEntry(b *strings.Builder, name string, t reflect.Type) {
	fmt.Fprintf(b, "  %s: {\n", name)
	for i := range t.NumField() {
		f := t.Field(i)
		jsonName := jsonFieldName(f)
		if !f.IsExported() || jsonName == "" {
			continue
		}
		code := schemaCode(f.Type)
		if hasOmitEmpty(f) {
			code += "?"
		}
		fmt.Fprintf(b, "    %s: %q,\n", jsonName, code)
	}
	b.WriteString("  },\n")
}

func schemaCode(t reflect.Type) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	switch t.Kind() {
	case reflect.Bool:
		return "b"
	case reflect.String:
		return "s"
	case reflect.Int, reflect.Int64:
		return "n"
	case reflect.Slice:
		return "a"
	case reflect.Struct, reflect.Map:
		return "o"
	default:
		return "u"
	}
}

func tsType(t reflect.Type, hint string) string {
	if hint != "" {
		return hint
	}
	if t == reflect.TypeFor[core.PlanListItem]() {
		return "PlanListItem"
	}
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.PkgPath() == "hdu-library-sniper/internal/api" {
		switch t.Name() {
		case "BookingAction", "PlanToggleAction", "BookingState", "NextTargetKind", "QrLoginPhase", "AppEventKind", "InvalidateTarget", "Weekday":
			return t.Name()
		}
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64:
		return "number"
	case reflect.Slice:
		return tsType(t.Elem(), "") + "[]"
	case reflect.Map:
		return "Record<string, unknown>"
	case reflect.Struct:
		return t.Name()
	default:
		return "unknown"
	}
}

func jsonFieldName(f reflect.StructField) string {
	tag := f.Tag.Get("json")
	if tag == "-" {
		return ""
	}
	name, _, _ := strings.Cut(tag, ",")
	if name == "" {
		return f.Name
	}
	return name
}

func hasOmitEmpty(f reflect.StructField) bool {
	_, rest, ok := strings.Cut(f.Tag.Get("json"), ",")
	return ok && strings.Contains(rest, "omitempty")
}
